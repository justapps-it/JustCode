// Embeds ./public into files.gen.js so the Worker serves the site by itself
// (no separate Workers Assets upload). Run before `wrangler deploy`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = path.join(site, 'public');
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.sh': 'text/plain; charset=utf-8',
  '.ps1': 'text/plain; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
};
const TEXT = new Set(['.html', '.js', '.css', '.svg', '.sh', '.ps1', '.txt']);
const out = {};
for (const name of fs.readdirSync(pub).sort()) {
  const ext = path.extname(name);
  if (!TYPES[ext]) continue;
  const buf = fs.readFileSync(path.join(pub, name));
  out['/' + name] = TEXT.has(ext) ? { type: TYPES[ext], text: buf.toString('utf8') } : { type: TYPES[ext], b64: buf.toString('base64') };
}
fs.writeFileSync(path.join(site, 'files.gen.js'), `// generated by tools/gen-files.mjs — do not edit\nexport const FILES = ${JSON.stringify(out)};\n`);
console.log(`embedded ${Object.keys(out).length} files`);
